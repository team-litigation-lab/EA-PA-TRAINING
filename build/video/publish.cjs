// Copies each built day video into the site (videos/dayN-narrated.mp4 + .vtt) and writes js/eapa-day-videos.js, the
// list the course's ▶ Video viewer reads (js/eapa-day-video.js). Generated: don't edit js/eapa-day-videos.js by hand.
//   node build/video/publish.cjs [videoOutDir]   (default build/video/out/video; each day in <dir>/dayN)
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '../..');
const SRC = process.argv[2] || path.join(__dirname, 'out/video');
const MAX = 25 * 1024 * 1024;   // a Workers static asset must be under 25 MiB
const out = {};
fs.mkdirSync(path.join(ROOT, 'videos'), { recursive: true });
for (let day = 1; day <= 10; day++) {
    const dir = path.join(SRC, 'day' + day);
    const web = path.join(dir, `day${day}-narrated-web.mp4`), vtt = path.join(dir, `day${day}-narrated.vtt`);
    const narr = path.join(__dirname, 'narration', `day${day}.json`);
    if (!fs.existsSync(web) || !fs.existsSync(vtt) || !fs.existsSync(narr)) continue;
    const size = fs.statSync(web).size;
    if (size >= MAX) { console.error(`Day ${day}: ${(size / 1048576).toFixed(1)} MB is over the 25 MB asset limit`); process.exit(1); }
    fs.copyFileSync(web, path.join(ROOT, 'videos', `day${day}-narrated.mp4`));
    fs.copyFileSync(vtt, path.join(ROOT, 'videos', `day${day}-narrated.vtt`));
    const slides = JSON.parse(fs.readFileSync(path.join(dir, 'slides.json'), 'utf8'));
    const spec = JSON.parse(fs.readFileSync(narr, 'utf8'));
    const cues = fs.readFileSync(vtt, 'utf8').match(/--> (\d+):(\d+):(\d+)\.(\d+)/g) || [];
    const last = cues.length ? cues[cues.length - 1].slice(4).split(/[:.]/).map(Number) : [0, 0, 0, 0];
    const duration = Math.ceil(last[0] * 3600 + last[1] * 60 + last[2] + last[3] / 1000 + 1);
    const v = Math.round(fs.statSync(web).mtimeMs / 1000).toString(36);
    out[day] = { title: spec.title, src: `/videos/day${day}-narrated.mp4?v=${v}`, captions: `/videos/day${day}-narrated.vtt?v=${v}`, duration,
        chapters: slides.map(s => ({ slide: s.slide, title: s.title, t: s.start })) };
    console.log(`Day ${day}: ${(size / 1048576).toFixed(1)} MB, ${Math.round(duration / 60)} min, ${slides.length} slides`);
}
fs.writeFileSync(path.join(ROOT, 'js/eapa-day-videos.js'),
    `/* Generated by build/video/publish.cjs — don't edit by hand. Each day's narrated video (build/video/README.md). */\n` +
    `window.EAPA_DAY_VIDEOS = ${JSON.stringify(out, null, 1)};\n`);
